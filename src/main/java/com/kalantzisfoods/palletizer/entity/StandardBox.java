package com.kalantzisfoods.palletizer.entity;

import jakarta.persistence.*;

@Entity
@Table(name = "standard_boxes")
public class StandardBox {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(name = "name")
    private String name;

    @Column(name = "category")
    private String category;

    @Column(name = "length")
    private Double length;

    @Column(name = "width")
    private Double width;

    @Column(name = "height")
    private Double height;

    @Column(name = "empty_weight")
    private Double emptyWeight;

    // Default constructor required by Hibernate
    public StandardBox() {}

    // --- GETTERS AND SETTERS ---
    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getCategory() { return category; }
    public void setCategory(String category) { this.category = category; }

    public Double getLength() { return length; }
    public void setLength(Double length) { this.length = length; }

    public Double getWidth() { return width; }
    public void setWidth(Double width) { this.width = width; }

    public Double getHeight() { return height; }
    public void setHeight(Double height) { this.height = height; }

    public Double getEmptyWeight() { return emptyWeight; }
    public void setEmptyWeight(Double emptyWeight) { this.emptyWeight = emptyWeight; }
}